def parse_name(raw_name, name_en_field):
    m = re.match(r'^\s*(.+?)\s*\(([^)]+)\)\s*$', raw_name)
    if m:
        name_ar, extracted_en = m.group(1), m.group(2)
    else:
        name_ar, extracted_en = raw_name, None
    name_en = name_en_field or extracted_en or name_ar
    return name_ar, name_en

def to_food_item(raw):
    tags = raw.get('tags') or ''
    tags_list = [t.strip() for t in tags.split(',') if t.strip()]
    category_raw = raw.get('category')
    category = CATEGORY_MAP.get(category_raw)
    fallback_category_used = False
    if category is None:
        category = 'condiment'
        fallback_category_used = True

    # تصحيح خطأ تصنيف مؤكد في المصدر (راجع docs/FOOD_DB_CONVERSION_REPORT.md §2.4):
    # food_3783 "قشطة" مصنَّف "ألبان ومشتقات" في المصدر، لكن الماكروز (كارب 25g،
    # سكر 22.5g، دهون 0.4g فقط، كالسيوم 3mg فقط، ألياف 2.4g) تطابق فاكهة القشطة
    # (Custard Apple/Sugar Apple) لا القشطة اللبنية. تم التأكيد يدويًا وتصحيحه هنا.
    if raw.get('food_id') == 'food_3783':
        category = 'fruit'

    name_ar, name_en = parse_name(raw['name'], raw.get('name_en'))

    # ---- meal types ----
    meal_type_raw = raw.get('meal_type')
    if meal_type_raw and meal_type_raw in MEAL_TYPE_MAP:
        suitable_meal_types = [MEAL_TYPE_MAP[meal_type_raw]]
    else:
        suitable_meal_types = CATEGORY_DEFAULT_MEAL_TYPES.get(category, ['any'])

    # ---- processing level ----
    nova = raw.get('nova')
    processing_level = NOVA_MAP.get(nova, 'minimally_processed')

    # ---- cuisine ----
    cuisine = CUISINE_MAP.get(raw.get('cuisine'), 'egyptian')

    # ---- medical suitability -> exclude / suitable / warnings ----
    unsuitable_for_conditions = set()
    suitable_for_conditions = set()
    warnings = []
    ms = raw.get('medical_suitability') or {}
    for src_key, value in ms.items():
        mapped = MEDICAL_MAP.get(src_key, [])
        if value == 'غير مناسب':
            unsuitable_for_conditions.update(mapped)
        elif value == 'مناسب':
            suitable_for_conditions.update(mapped)
        elif value in ('بحذر', 'حذر', 'بكمية محدودة'):
            warnings.append(f'{src_key}: {value}')
        # 'غير محدد' -> تجاهل، مفيش معلومة كافية

    # health_flags تحذيرات إضافية (نصية فقط، مش استبعاد)
    health_flags_raw = raw.get('health_flags')
    if health_flags_raw:
        for flag in health_flags_raw.split(','):
            flag = flag.strip()
            if flag.startswith('تحذير_'):
                warnings.append(flag.replace('تحذير_', 'تحذير: '))

    # ---- allergens ----
    allergens = detect_allergens(raw['name'], category_raw, tags_list)
    if raw.get('food_id') == 'food_3783':
        allergens = [a for a in allergens if a != 'lactose']  # فاكهة، مش ألبان — راجع override الفئة أعلاه

    # ---- diet styles ----
    is_fasting_tagged = 'صيامي' in tags_list  # إشارة موثوقة نسبيًا لغياب كل المنتجات الحيوانية
    has_meat_tag = 'contains_meat' in tags_list
    has_chicken_tag = 'contains_chicken' in tags_list
    has_fish_tag = 'contains_fish' in tags_list or 'fish' in allergens
    is_dairy_or_egg = category == 'dairy' or 'egg' in allergens
    is_animal_based = has_meat_tag or has_chicken_tag or has_fish_tag or is_dairy_or_egg or category == 'protein'

    unsuitable_for_diets = set()
    suitable_for_diets = set()

    # VEGAN: صيامي تمس أولوية أعلى من contains_meat/chicken (اكتُشفت 4 حالات تعارض فعلية —
    # أطباق "كفتة نباتية بديلة" اتعلّمت contains_meat غلط بسبب اسم الطبق، رغم كونها صيامي فعليًا)
    if is_fasting_tagged:
        suitable_for_diets.update(['vegan', 'vegetarian'])
    elif is_animal_based:
        unsuitable_for_diets.add('vegan')
        if has_meat_tag or has_chicken_tag or has_fish_tag:
            unsuitable_for_diets.add('vegetarian')
        else:
            suitable_for_diets.add('vegetarian')  # ألبان/بيض بدون لحم فعلي
    else:
        suitable_for_diets.update(['vegan', 'vegetarian'])

    # PESCATARIAN: يستبعد اللحم/الدجاج فقط، السمك والألبان مسموحين
    if (has_meat_tag or has_chicken_tag) and not is_fasting_tagged:
        unsuitable_for_diets.add('pescatarian')

    # CARNIVORE: مسموح فقط للمنتجات الحيوانية
    if not (category in ('protein', 'dairy') or has_fish_tag):
        unsuitable_for_diets.add('carnivore')

    # KETO / LOW_CARB: حسب صافي الكارب (كارب - ألياف)
    carb_g = raw.get('carb_g') or 0
    fiber_g = raw.get('fiber_g') or 0
    net_carb = max(0, carb_g - fiber_g)
    if net_carb > 10:
        unsuitable_for_diets.add('keto')
    if net_carb > 20:
        unsuitable_for_diets.add('low_carb')

    # LOW_SODIUM / LOW_FAT
    sodium_mg = raw.get('sodium_mg') or 0
    fat_g = raw.get('fat_g') or 0
    if sodium_mg > 400:
        unsuitable_for_diets.add('low_sodium')
    if fat_g > 17.5:
        unsuitable_for_diets.add('low_fat')

    # ---- religious tags ----
    # رمضان: قيد توقيت لا قيد نوع طعام -> كل الأصناف مؤهلة افتراضيًا
    religious_tags = {'ramadan_suhoor', 'ramadan_iftar'}
    if is_fasting_tagged:
        religious_tags.add('christian_fast_strict')
    elif has_fish_tag and not (has_meat_tag or has_chicken_tag) and category != 'dairy':
        religious_tags.add('christian_fast_fish_allowed')

    def g(key, default=0.0):
        v = raw.get(key)
        return float(v) if v is not None else default

    food_item = {
        'id': raw['food_id'],
        'name_ar': name_ar,
        'name_en': name_en,
        'category': category,
        'ingredients': [],
        'reference_amount_g': 100,
        'macros': {
            'kcal': g('kcal'), 'protein_g': g('protein_g'), 'carbs_g': g('carb_g'), 'fat_g': g('fat_g'),
            'fiber_g': g('fiber_g'), 'sugar_g': g('sugar_g'), 'added_sugar_g': 0,
            'saturated_fat_g': g('saturated_fat_g'), 'monounsaturated_fat_g': g('monounsaturated_fat_g'),
            'polyunsaturated_fat_g': g('polyunsaturated_fat_g'), 'cholesterol_mg': g('cholesterol_mg'),
            'omega3_mg': g('omega3_g') * 1000,
        },
        'micros': {
            'sodium_mg': g('sodium_mg'), 'potassium_mg': g('potassium_mg'), 'calcium_mg': g('calcium_mg'),
            'magnesium_mg': g('magnesium_mg'), 'iron_mg': g('iron_mg'), 'zinc_mg': g('zinc_mg'),
            'selenium_mcg': g('selenium_mcg'), 'vitamin_a_mcg': g('vitamin_a_mcg'),
            'vitamin_b12_mcg': g('vitamin_b12_mcg'), 'vitamin_c_mg': g('vitamin_c_mg'),
            'vitamin_d_mcg': g('vitamin_d_mcg'), 'vitamin_e_mg': g('vitamin_e_mg'), 'vitamin_k_mcg': g('vitamin_k_mcg'),
            'phosphorus_mg': g('phosphorus_mg'),
        },
        'gi': raw.get('gi') if raw.get('gi') is not None else -1,
        'gl': raw.get('gl') if raw.get('gl') is not None else -1,
        'quality_score': round(raw.get('quality_score') or 50.0, 1),
        'processing_level': processing_level,
        'suitable_meal_types': suitable_meal_types,
        'cuisine': cuisine,
        'allergens': allergens,
        'unsuitable_for_conditions': sorted(unsuitable_for_conditions),
        'suitable_for_conditions': sorted(suitable_for_conditions),
        'unsuitable_for_diets': sorted(unsuitable_for_diets),
        'suitable_for_diets': sorted(suitable_for_diets),
        'religious_tags': sorted(religious_tags),
        'warnings': warnings,
        'typical_portion_desc_ar': CATEGORY_DEFAULT_PORTION.get(category, 'حصة ~100 جم'),
    }
    return food_item, fallback_category_used

