def word_pattern(*words):
    return re.compile('|'.join(re.escape(w) for w in words))

ALLERGEN_PATTERNS = {
    'egg': re.compile(r'(?<![أإا])بيض(?!اء)'),
    'gluten': word_pattern('قمح', 'شعير', 'جاودار', 'برغل', 'فريك', 'سميد', 'مكرونة', 'معكرونة',
                            'خبز', 'بسكويت', 'كسكس', 'فريكة', 'عيش', 'شعرية'),
    'sesame': word_pattern('سمسم', 'طحينة', 'طحينية'),
    'soy': word_pattern('صويا', 'توفو', 'ميسو', 'تمبيه', 'إداماميه', 'ادامامي'),
    # ملاحظة: 'لوز' (لوز = حساسية اللوز) بتتفعّل عبر نمط مخصوص تحت الشرط
    # 'nuts_almond' لتفادي فخ "الوز/الوزغة" (إوز، سحلية) اللي بيحتوي "لوز"
    # كسلسلة فرعية زي فخ بيض/أبيض بالظبط — راجع docs/FOOD_DB_CONVERSION_REPORT.md
    'nuts': word_pattern('جوز الهند طبيعي', 'كاجو', 'فستق', 'بندق', 'بقان', 'مكاديميا', 'جوز عادي', ' جوز ', 'جوز،', 'جوز)', 'مكسرات'),
    'nuts_almond': re.compile(r'اللوز|(?<!ا)لوز(?!غة)'),
    'fish': word_pattern('سمك', 'تونة', 'سلمون', 'بلطي', 'بوري', 'ماكريل', 'سردين', 'أنشوجة', 'فسيخ', 'رنجة'),
    'shellfish': word_pattern('جمبري', 'جمبرى', 'روبيان', 'قريدس', 'استاكوزا', 'سرطان البحر', 'محار', 'بلح البحر', 'قشريات', 'كابوريا'),
}

def detect_allergens(name, category_raw, tags):
    found = set()
    text = name
    for allergen, pattern in ALLERGEN_PATTERNS.items():
        if pattern.search(text):
            found.add('nuts' if allergen == 'nuts_almond' else allergen)
    if category_raw in ('ألبان ومشتقات', 'ألبان وأجبان', 'ألبان'):
        found.add('lactose')
    if 'contains_fish' in tags:
        found.add('fish')
    return sorted(found)

